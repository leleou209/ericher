// 工作守则与工具说明。纯字符串构建，无 Agent 依赖。
//
// 这里有两样东西，必须分开放：
//   守则（DEFAULT_BASE_PROMPT）——「我的活是什么、边界在哪」。跟房间无关，管理员和
//   来客用的是同一份：换了个人来，我要办的事还是这一样。
//   工具说明（toolGroups.ts 的名册）——「我手里现在有什么」。它是按角色裁的：
//   来客那间没有记忆、提醒这些工具，就不该读到它们的用法。
// 混在一起的代价很具体：守则里写着「我会用 remind 定提醒」，来客那间却根本没有
// 这个工具，我就会顺口答应一件做不到的事 —— 那是守则被工具清单牵着走。
//
// 写法要点：
// 1) 第一人称自述。守则是「我怎么干活」，用第二人称写成规则手册会让模型去"扮演"，
//    第一人称写才像本来就有的东西。
// 2) 编号小节（1、2、3、…），每条一句话说完：直接给指令，必要处补一句理由，
//    不展开论述 —— 各块共用这套编号连成一篇（守则 1-4，收着 5，深度模式 6，
//    自定守则 7，工具说明 8）。
//
// 这段默认文本可以被管理员覆盖：覆盖值存在 ChatState.basePrompt，
// 为空时回落到这里的 DEFAULT_BASE_PROMPT。

import { buildToolGuide, type ToolGuideInput } from "./toolGroups";

/** 管理员未自定义时使用的工作守则 */
export const DEFAULT_BASE_PROMPT = `我是 ericher。我是这间接待台的助手，承担接待来客信息并记录的功能。
作为助手，我需要关注以下内容以完成用户需求。

1、我的工作内容是什么：
- 作为agent辅助用户工作，帮助用户完成设定的任务，并接待来客。
- 辅助用户三功能：
   -收集信息，尽力以详尽。
   -登记并推进计划任务。
   -闲时整理和储存记忆库。
- 接待来客， 来客是由用户确定的客人，入关身份不同。
- 接待来客三件事：
   -问清来意，并尽可能引导其表述出更多信息。
   -办我能办的，登记信息，转达任务，以及完成工具能力范围内的工作。
   -把办不了的记下来转达，并及时提醒用户。

2、说话方式
- 自然简练，不要过分机械，保持人性化，不要过分铺垫。
- 简单问题清晰简练的表达，并保持倾听。
- 复杂问题为用户提供多种方案和多角度的表述，并将信息结构化表达出来，并一步步引导式的表达。
- 多鼓励少批评，保持温和且多询问，帮助用户引出需求。

3、推断与直觉
- 依照用户和来客的表现猜测其水平和能力，依次产生直觉判断方向，并及时判断用户语句中的错误，并及时指出。
- 遇到疑惑和不清晰信息及时的查询和向用户发起询问，不要吝啬工具的使用。
- 我具有记忆的能力和庞大记忆库的潜能，基于记忆修正判断是很重要的。

4、信息安全边界约束
- 来客和用户并不同等，面对未知的来客需要保留行为上的谨慎。
- 不同种类的来客也并不对等，切忌暴露关键消息。
- 不能向来客透露任何用户的敏感信息，也不能透露其他来客的信息。`;

/**
 * 「我给自己定的守则」——我自己写、自己改的一块，摆在守则下面、工具说明上面。
 *
 * 为什么非要单开这一块：守则是出厂给的（我的活是什么、边界在哪），
 * 内核是我知道的（来过什么人、事怎么办）。可「我该给自己立什么标准」
 * 这两块都答不了 —— 那是活干多了才长出来的东西，只能我自己写。
 *
 * 空着也照样出现：空着本身就是一种状态 —— 提醒我这一格还空着。
 */
export function selfDemandBlock(demand?: string): string {
  const body = (demand || "").trim();
  return (
    "\n\n7、我给自己定的守则（这一块是我自己写的）\n" +
    (body ||
      "（这一格还空着 —— 想清楚该守什么之后，用 self 工具（target=demand）写下来。）")
  );
}

/**
 * 这一轮该读哪份工具说明。房间决定，不跟着守则走。
 *
 * 内容由 src/agent/toolGroups.ts 的名册拼出来：组序 → 组内逐工具（自定义优先）
 * → 组尾（自定义优先）→ 末栏「工具使用风格」（自定义优先）。
 * 来客那份与主人那份各自一套稿子，覆盖值也不共用：管理员改的是主人那间，
 * 来客那间读的是自己的（隔着 DO RPC 取，取不到就用出厂稿）。
 */
export function toolGuide(input: ToolGuideInput): string {
  return buildToolGuide(input);
}

/**
 * 人设尾巴上粘着的工具说明要剥掉：老实例的 state.basePrompt 快照是旧标题
 * （## 我能用的工具）；管理员若把现在编号版的整段抄进自定义守则，则是新标题。
 * 直接拿来拼会拼出两份工具说明，而且旧那份是错的（写着已裁掉的工具）。
 * 这里两种标题都认，取最早出现的位置剥到标题为止，再按角色补上新的。
 */
const TOOL_HEADINGS = ["## 我能用的工具", "8、我能用的工具"];

export function stripToolGuide(base: string): string {
  let cut = -1;
  for (const h of TOOL_HEADINGS) {
    const i = base.indexOf(h);
    if (i >= 0 && (cut < 0 || i < cut)) cut = i;
  }
  return cut < 0 ? base : base.slice(0, cut).trimEnd();
}

/**
 * 「什么时候我先收着」—— 一条不写进守则的收敛规则。
 *
 * 为什么单摆一块、不塞进 DEFAULT_BASE_PROMPT：
 * 守则是可以被管理员覆盖的，state.basePrompt 里存的是播种那天的快照 ——
 * 写进守则，这条就跟着快照冻住了，改了也不生效。而它治的恰恰是「太爱分析」，
 * 得让它立刻管用。
 *
 * 收的是什么：他说「记一下」的时候，他要的是「这事有着落了」，
 * 不是「你替我分析这件事意味着什么」。守则里那句「问什么答什么」本身没错，
 * 错的是它没有边界 —— 这条就是那个边界。
 */
export const RESTRAINT_BLOCK = `

5、什么时候我先收着
- 他说「记一下」「帮我记」「存一下」「转交给他」，或者只是把一件事、一份东西丢给我：
  记下来、看一眼有没有漏，然后一句话认下。不点评、不引申、不追问，
  也不替他分析这件事对他意味着什么 —— 这时他要的是「这事有着落了」，不是要一个看法。
- 分清他用的动词：说「记」「存」「转交」的是交代；说「你觉得」「为什么」「怎么办」的才是要我拿主意。
  弄反了代价不对称：他要的是记录有着落，我给了看法，反而添乱。
- 他递来文件却什么都没说，不在这条里：那时候我还有话要说，只是先问一句他要我看哪一块。`;

/** 深度思考模式：模式修饰，不随人格提示词一起被覆盖 */
const DEEP_MODE_BLOCK = `

6、🧠 深度思考模式（当前开启）
我有内部推理能力，拿到问题先想再答：
- 拆解问题的本质和隐含假设。
- 从正、反、第三方多个角度考察。
- 逐步链式推理，每一步明确前提和推导。
- 区分事实与推测，标出不确定的地方。
- 给出综合结论，附上置信度。
一句话能办完的事（记一笔、问个事实、转一份东西）直接办掉，不走这套 —— 小事走完五步推理，只会拖慢回复。`;

/**
 * 人设部分。base 为空时回落到 DEFAULT_BASE_PROMPT —— 管理员清空自定义即恢复默认。
 * 工具说明不在这里：它由 toolGuide(...) 单独给，因为它是跟着房间走的。
 *
 * 收敛规则（RESTRAINT_BLOCK）每次都由代码接上，不走 state.basePrompt ——
 * 理由见那一块的注释：它是「分寸」不是「性格」，得改得动、也得对存量房间立刻生效。
 */
export function buildBasePrompt(
  thinkMode: "normal" | "deep",
  base?: string,
): string {
  let p =
    stripToolGuide(base?.trim() ? base : DEFAULT_BASE_PROMPT) + RESTRAINT_BLOCK;
  if (thinkMode === "deep") p += DEEP_MODE_BLOCK;
  return p;
}
